"""Render per-host service TOMLs, the ansible inventory and env group_vars
from cluster.toml + allocation + terraform outputs.

Projection map — which cluster.toml service tables reach which service —
mirrors how the boxd binaries share one BoxdConfig schema.
"""
from . import clouds, local_ca, telemetry, toml_emit
from .config import OIDC_REQUIRED, resolver_addr, rust_trim
from .util import InstallError

ACME_DIRECTORIES = {
    "gts": "https://dv.acme-v02.api.pki.goog/directory",
    "zerossl": "https://acme.zerossl.com/v2/DV90",
}
# Local leaves live 30 days (boxd's default leaf_days); renew with 10 left.
LOCAL_CA_RENEWAL_DAYS = 10
FORCED_BILLING = {"credits_signup": False, "cardless_signup": True}
HEADER = "GENERATED by the boxd installer — do not edit; edit cluster.toml and re-run render."

def oidc_render_error(table: dict) -> str | None:
    """Why the merged [oidc] table (cluster.toml's keys and the providers
    config's client_secret) can't go to the console, or None. boxd-console
    refuses to start on one with issuer, client_id, display_name or
    client_secret empty. `apply` asks before terraform, the render again."""
    missing = [k for k in (*OIDC_REQUIRED, "client_secret")
               if not rust_trim(str(table.get(k, "")))]
    if not missing:
        return None
    if set(table) == {"client_secret"}:
        return ("the providers config has [oidc].client_secret, but cluster.toml has no "
                "[oidc]. To turn single sign-on off, remove [oidc] from the providers config "
                "too (`providers edit`); to keep it, put [oidc] back in cluster.toml")
    return (f"[oidc] has no {', '.join(missing)}: issuer, client_id and display_name go in "
            "cluster.toml's [oidc], client_secret in the providers config (`providers edit`)")

SHARED = {
    "resend":    {"control", "proxy", "console"},
    "analytics": {"control", "proxy", "worker", "console"},
    "backups":   {"control", "proxy", "worker"},
    # Only control and worker read it, so proxies never hold the key.
    "snapshot_archive": {"control", "worker"},
}

class Renderer:
    def __init__(self, cfg, alloc, tf_out: dict, state, assets_root: str | None = None):
        self.cfg = cfg
        self.alloc = alloc
        self.tf = tf_out
        self.state = state
        self.assets_root = assets_root
        self.kek = state.secrets_kek()
        self.jwt = state.jwt_secret()

    def _advertised_ip(self, node) -> str:
        """The IP clients are told to dial (proxy public_ips, dns records,
        glue): the node's public IP, or with private ingress its internal one
        (proxies bind 0.0.0.0, so only what is advertised changes)."""
        ip = self.tf["nodes"].get(node.name, {}).get("external_ip")
        if ip:
            return ip
        if self.cfg.ingress == "private":
            return node.internal_ip
        raise InstallError(f"{node.name}: no external IP in terraform outputs (role needs one)")

    def _cluster_block(self, with_learners: bool = True) -> dict:
        block = {"peers": self.alloc.peers()}
        if with_learners:
            block["learners"] = self.alloc.learners()
        return block

    def _base(self, node, role: str, storage_role: str | None = None) -> dict:
        doc = {
            "node_id": self.alloc.node_id(node.name, role),
            "zone": self.cfg.zone,
            "self_hosted": True,
        }
        if role != "dns":
            doc["secrets_kek"] = self.kek
        sr = storage_role or role
        doc["cluster"] = self._cluster_block(with_learners=(role != "console"))
        doc["vrack"] = {"interface": self.cfg.interface, "subnet": self.cfg.vpc_cidr}
        doc["storage"] = {
            "raft_dir": f"/var/lib/boxd/{sr}/raft",
            "state_db": f"/var/lib/boxd/{sr}/state.db",
        }
        doc["network"] = {
            "vni_range_start": self.cfg.network["vni_range_start"],
            "vni_range_end": self.cfg.network["vni_range_end"],
        }
        return doc

    def _shared_tables(self, service: str) -> dict:
        out = {}
        for tbl, consumers in SHARED.items():
            if service not in consumers:
                continue
            val = self.cfg.table(tbl)
            if not val and tbl == "backups":
                val = self.tf.get("backups") or {}
            if not val and tbl == "analytics":
                val = self._auto_analytics()
            if tbl == "snapshot_archive":
                val = self._snapshot_archive()
            if val:
                out[tbl] = dict(val)
        return out

    def _snapshot_archive(self) -> dict:
        """The store from terraform (AWS, auto) under the providers fields,
        plus archive_dir from cluster.toml. Declared but incomplete is an
        error: boxd would start with the archive half-configured."""
        from .config import ARCHIVE_STORE_KEYS
        if not self.cfg.snapshot_archive_declared():
            return {}
        val = {**(self.tf.get("snapshot_archive") or {}), **self.cfg.table("snapshot_archive")}
        missing = [k for k in ARCHIVE_STORE_KEYS if not val.get(k)]
        if missing:
            raise InstallError(
                f"[snapshot_archive] is declared but has no {', '.join(missing)}: on AWS the "
                "installer creates the bucket (unless [aws] auto_snapshot_archive = false); "
                "otherwise set the store fields with `providers edit`")
        return val

    def _auto_analytics(self) -> dict:
        """A metrics role in the topology implies [analytics] — workers
        stream per-VM cpu/mem/disk samples there and the console reads the
        usage graphs from it. An explicit [analytics] (providers overlay or
        cluster.toml, e.g. an external ClickHouse) wins over this."""
        ch = self.cfg.nodes_with("metrics")
        if not ch:
            return {}
        return {"endpoint": f"http://{ch[0].internal_ip}:8123",
                "user": "default",
                "password": self.state.clickhouse_password()}

    def _github_key_stored(self) -> bool:
        import os
        return os.path.exists(os.path.join(self.state.keys_dir, "github-app.pem"))

    def _github_table(self) -> dict:
        """[github] from the providers overlay, with the App private key path
        pointed at where ansible ships the PEM (see `providers set-github-key`).
        The path is only meaningful if the PEM is actually in state — fail the
        render rather than deploy a console that can't load its key."""
        t = dict(self.cfg.table("github"))
        if not (t.get("client_id") and t.get("client_secret")):
            raise InstallError(
                "[github] needs client_id AND client_secret (the OAuth sign-in "
                "pair; a GitHub App's own client credentials work) — the boxd "
                "binaries refuse a [github] table without them. app_* alone is "
                "not a valid config; set both via `providers edit`")
        if t.get("app_id"):
            if not self._github_key_stored():
                raise InstallError(
                    "[github].app_id is set but no App private key is stored — "
                    "run `./install.py providers set-github-key <key>.pem`")
            t.setdefault("app_private_key_path", "/etc/boxd/tls/github-app.pem")
        return t

    def _oidc_table(self) -> dict:
        """[oidc] for the console: cluster.toml's keys plus client_secret from
        the providers config."""
        t = dict(self.cfg.table("oidc"))
        if why := oidc_render_error(t):
            raise InstallError(why)
        return t

    def _proxy_host(self, node) -> str:
        """This proxy's own dial name (p0.<zone>, p1.<zone>, …) — published via
        ListProxyNodes so clients dial a NAME: an IP-literal authority sends no
        SNI and the proxy rejects the handshake. Covered by the zone
        wildcard cert."""
        proxies = self.cfg.nodes_with("proxy")
        idx = next(i for i, n in enumerate(proxies) if n.name == node.name)
        return f"p{idx}.{self.cfg.zone}"

    def _names_table(self) -> dict:
        """[names] with the per-proxy labels force-reserved — a user VM named
        p0 would shadow the proxy's dial record."""
        t = dict(self.cfg.table("names"))
        reserved = list(t.get("reserved", []))
        for i in range(len(self.cfg.nodes_with("proxy"))):
            if f"p{i}" not in reserved:
                reserved.append(f"p{i}")
        t["reserved"] = reserved
        return t

    def _routes(self) -> list[dict]:
        """One source of truth for SNI routes AND dns service records."""
        routes = []
        consoles = self.cfg.nodes_with("console")
        if consoles:
            ip = consoles[0].internal_ip
            routes.append({"hostname": f"app.{self.cfg.zone}", "target_ip": ip, "target_port": 8080})
            routes.append({"hostname": f"connect.{self.cfg.zone}", "target_ip": ip, "target_port": 8080})
        routes.extend(self.cfg.table("proxy").get("internal_services", []))
        return routes

    def _cluster_org_name(self) -> str:
        return rust_trim(str(self.cfg.doc["cluster"].get("org_name") or ""))

    def control_doc(self, node) -> dict:
        doc = self._base(node, "control")
        # Control's self-host sweeper gives the cluster org the slug of this
        # name while it still has the one the first sign-in generated.
        if org_name := self._cluster_org_name():
            doc["cluster_org_name"] = org_name
        doc["control"] = dict(self.cfg.table("control"))
        if self.cfg.table("names"):
            doc["names"] = self._names_table()
        doc["acme"] = self._acme_table()
        doc["billing"] = FORCED_BILLING.copy()
        # Where the cluster runs, for the hourly report, and the node default
        # when telemetry is off (before the converge: no send before `off`).
        doc["telemetry"] = telemetry.control_table(self.cfg)
        doc.update(self._shared_tables("control"))
        auto = self.cfg.table("automations")
        if auto:
            doc["automations"] = {"composio_api_key": auto["composio_api_key"]}
            for k in ("anthropic_api_key", "docs_model"):
                if k in auto:
                    doc["automations"][k] = auto[k]
        return doc

    def _acme_table(self) -> dict:
        ca = self.cfg.acme_ca
        table = self.cfg.table("acme")
        if ca == "local":
            # No contact_email, directory or EAB: an older boxd-control that
            # doesn't know local mode fails to parse this (contact_email is
            # required there) instead of starting against a public CA.
            if not local_ca.stored(self.state.keys_dir):
                raise InstallError(
                    '[acme].ca = "local" but no CA is stored — run '
                    "`./install.py providers set-tls-ca <cert.pem> <key.pem>`")
            acme = {
                "renewal_days": LOCAL_CA_RENEWAL_DAYS,
                "local_ca": {
                    "cert_path": f"{local_ca.REMOTE_DIR}/{local_ca.CERT_FILE}",
                    "key_path": f"{local_ca.REMOTE_DIR}/{local_ca.KEY_FILE}",
                },
            }
        else:
            contact = table["contact_email"]
            eab = self.state.acme_eab(ca, project=self.cfg.cloud.get("project"), email=contact)
            acme = {
                "directory_url": ACME_DIRECTORIES[ca],
                "contact_email": contact,
                "eab_kid": eab["kid"],
                "eab_hmac_key": eab["hmac"],
                "eab_single_use": ca == "gts",
            }
        if "dns_verify_resolver" in table:
            acme["dns_verify_resolver"] = resolver_addr(table["dns_verify_resolver"])
        return acme

    def proxy_doc(self, node) -> dict:
        doc = self._base(node, "proxy")
        p = dict(self.cfg.table("proxy"))
        p.pop("internal_services", None)
        tailscale = p.pop("tailscale", None)
        netbird = p.pop("netbird", None)
        proxy = {
            "public_interface": self.cfg.interface,
            "public_ips": [self._advertised_ip(node)],
            "public_host": self._proxy_host(node),
            "ip_pool": [],
            **p,
            "internal_services": self._routes(),
        }
        if tailscale is not None:
            proxy["tailscale"] = {"hostname": f"boxd-{self.cfg.name}-{node.name}", **tailscale}
        if netbird is not None:
            proxy["netbird"] = {"device_name": f"boxd-{self.cfg.name}-{node.name}", **netbird}
        if tailscale is not None or netbird is not None:
            proxy["internal_services"] = proxy.pop("internal_services")
        doc["proxy"] = proxy
        if self.cfg.table("names"):
            doc["names"] = self._names_table()
        doc["api"] = {"jwt_secret": self.jwt}
        if self.cfg.table("github"):
            doc["github"] = self._github_table()
        doc.update(self._shared_tables("proxy"))
        return doc

    def dns_doc(self, node) -> dict:
        doc = self._base(node, "dns")
        d = {
            "zone": self.cfg.zone,
            "listen": self.cfg.table("dns").get("listen", "0.0.0.0:53"),
            "alias_zones": self.cfg.table("dns").get("alias_zones", []),
            "static_records": self._dns_records(),
        }
        doc["dns"] = d
        return doc

    def _dns_records(self) -> list[dict]:
        records = []
        for slot, node in sorted(self._ns_map().items()):
            records.append({"name": slot, "type": "A", "value": self._advertised_ip(node), "ttl": 86400})
        for i, n in enumerate(self.cfg.nodes_with("proxy")):
            records.append({"name": f"p{i}", "type": "A", "value": self._advertised_ip(n), "ttl": 300})
        proxies = self.cfg.nodes_with("proxy")
        for route in self._routes():
            label = route["hostname"].removesuffix("." + self.cfg.zone)
            for p in proxies:
                records.append({"name": label, "type": "A", "value": self._advertised_ip(p), "ttl": 300})
        records.extend(self.cfg.table("dns").get("static_records", []))
        return records

    def _ns_map(self) -> dict:
        return {n.qualifiers["dns"]: n for n in self.cfg.nodes_with("dns")}

    def worker_doc(self, node) -> dict:
        doc = self._base(node, "worker")
        doc["network"]["bridge_subnet"] = self.alloc.bridge_subnet(node.name)
        doc["paths"] = {"run_dir": "/run/boxd", "data_dir": "/mnt/boxd-data", "log_dir": "/var/log/boxd"}
        worker = dict(self.cfg.table("worker"))
        for k in ("warm_slots", "nested_virt", "tc_filters"):
            if k in node.raw:
                worker[k] = node.raw[k]
        doc["worker"] = worker
        doc["api"] = {"jwt_secret": self.jwt}
        if self.cfg.table("github"):
            doc["github"] = {"client_id": "", "client_secret": "",
                             **{k: v for k, v in self._github_table().items()
                                if k.startswith("app_")}}
        doc.update(self._shared_tables("worker"))
        auto = self.cfg.table("automations")
        if auto:
            doc["automations"] = {"composio_api_key": auto["composio_api_key"]}
        return doc

    def console_doc(self, node) -> dict:
        doc = self._base(node, "console", storage_role="console-replica")
        doc["signups_open"] = True
        # The cluster org takes it when the first sign-in creates it.
        if org_name := self._cluster_org_name():
            doc["cluster_org_name"] = org_name
        doc["api"] = {"jwt_secret": self.jwt}
        if self.cfg.table("google"):
            doc["google"] = dict(self.cfg.table("google"))
        if self.cfg.table("github"):
            doc["github"] = self._github_table()
        # Single sign-on: only the console reads it. With it, the console
        # refuses GitHub and Google sign-in.
        if self.cfg.table("oidc"):
            doc["oidc"] = self._oidc_table()
        doc.update(self._shared_tables("console"))
        doc["billing"] = FORCED_BILLING.copy()
        auto = self.cfg.table("automations")
        if auto:
            a = {
                "composio_api_key": auto["composio_api_key"],
                "webhook_secret": self.state.automations_webhook_secret(),
                "connect_domain": f"connect.{self.cfg.zone}",
            }
            cache = self.state.data.get("composio_auth_configs")
            if cache:
                a["auth_configs"] = cache
            doc["automations"] = a
        return doc

    def deploy_configs(self) -> dict[str, str]:
        docs = {"control": self.control_doc, "proxy": self.proxy_doc,
                "dns": self.dns_doc, "worker": self.worker_doc,
                "console": self.console_doc}
        out = {}
        for node in self.cfg.nodes:
            for role in node.roles:
                if role in docs:
                    out[f"deploy-config/{node.name}/{role}.toml"] = \
                        toml_emit.dumps(docs[role](node), header=HEADER)
        return out

    def inventory(self) -> str:
        cfg, alloc = self.cfg, self.alloc
        lines = [
            "# GENERATED by the boxd installer — do not edit.",
            "all:",
            "  vars:",
            "    ansible_user: ubuntu",
            f"    ansible_ssh_private_key_file: {self.state.keys_dir}/boxd-deploy",
        ]
        # metal: direct ssh to each node's ansible_host, no tunnel.
        if proxy_cmd := clouds.get(cfg).ssh_proxy_command(cfg):
            lines += ["    ansible_ssh_common_args: >-",
                      f'      -o ProxyCommand="{proxy_cmd}"']
        lines.append("  children:")
        for group in ("control", "proxy", "console", "dns", "worker", "metrics"):
            nodes = cfg.nodes_with(group)
            if not nodes:
                continue
            lines.append(f"    {group}:")
            lines.append("      hosts:")
            for n in nodes:
                hv = {**clouds.get(cfg).host_vars(n, self.tf),
                      "vrack_ip": n.internal_ip, "node_id": alloc.node_id(n.name, n.primary_role)}
                if group == "worker":
                    hv["bridge_subnet"] = alloc.bridge_subnet(n.name)
                    hv["bridge_gateway"] = alloc.bridge_gateway(n.name)
                pairs = ", ".join(f"{k}: {v}" for k, v in hv.items())
                lines.append(f"        {n.name}: {{ {pairs} }}")
        lines.append(f"    {cfg.env_group}:")
        lines.append("      hosts:")
        for n in cfg.nodes:
            lines.append(f"        {n.name}: {{}}")
        return "\n".join(lines) + "\n"

    def group_vars(self) -> str:
        cfg = self.cfg
        lines = [
            "# GENERATED by the boxd installer — do not edit.",
            f"vrack_interface: {cfg.interface}",
            f"public_interface: {cfg.interface}",
        ]
        if self._github_key_stored():
            lines.append("boxd_github_app_key: github-app.pem")
        if cfg.acme_ca == "local":
            lines.append("boxd_local_ca: true")
        if cfg.nodes_with("metrics"):
            lines += [
                f"clickhouse_password: {self.state.clickhouse_password()}",
                f"clickhouse_allowed_network: {cfg.vpc_cidr}",
            ]
        lines += [
            "",
            "boxd_workers:",
        ]
        for n in cfg.nodes_with("worker"):
            lines.append(
                f"  - {{ name: {n.name}, vrack_ip: {n.internal_ip}, "
                f"bridge_subnet: {self.alloc.bridge_subnet(n.name)}, vni: {self.alloc.vnis[n.name]} }}")
        if cfg.nodes_with("worker"):
            lines += [
                "",
                "# Swap = the capacity tier idle guest pages park in (workers run",
                "# deliberately oversubscribed). On the data disk — the 50G boot disk",
                "# cannot hold it.",
                "boxd_worker_swapfiles:",
                "  - { path: /mnt/boxd-data/swap0, size: 64G }",
            ]
        return "\n".join(lines) + "\n"

    def downloads(self) -> dict[str, str]:
        """CLI install artifacts served at app.<zone>/downloads. The binaries
        (all platforms) and the upstream
        install script template come from the assets zip; this renders the
        per-zone manifests and parameterizes the script."""
        import hashlib
        import json
        import os
        import re as _re
        if not self.assets_root:
            return {}
        cli_dir = os.path.join(self.assets_root, "cli")
        tpl_path = os.path.join(cli_dir, "install-template.sh")
        if not os.path.isdir(cli_dir) or not os.path.exists(tpl_path):
            return {}
        with open(os.path.join(self.assets_root, "MANIFEST.json")) as fh:
            m = json.load(fh)
        version = m.get("cli", {}).get("version", m["git_sha"][:8])
        zone = self.cfg.zone
        base = f"https://app.{zone}/downloads/cli"
        files: dict[str, str] = {}
        for name in sorted(os.listdir(cli_dir)):
            if not name.startswith("boxd-") or name.endswith(".sh"):
                continue
            platform = name[len("boxd-"):]
            h = hashlib.sha256()
            with open(os.path.join(cli_dir, name), "rb") as fh:
                for chunk in iter(lambda: fh.read(1 << 20), b""):
                    h.update(chunk)
            files[f"downloads/cli/latest-{platform}.json"] = json.dumps({
                "version": version,
                "url": f"{base}/{name}",
                "sha256": h.hexdigest(),
            }, indent=1) + "\n"
        if not files:
            return {}
        files["downloads/cli/cli-version.txt"] = version + "\n"
        tpl = open(tpl_path).read()
        tpl, n = _re.subn(r'^BASE_URL=".*"$', f'BASE_URL="{base}"', tpl, count=1, flags=_re.M)
        if n != 1:
            raise InstallError("install-template.sh: BASE_URL line not found")
        tpl += f"""
"${{BINARY_PATH}}" config set api-url "https://{zone}" >/dev/null 2>&1 \
    && echo "  - api-url set to https://{zone}" \
    || echo "  ! run: ${{BINARY_NAME}} config set api-url https://{zone}"
"""
        files["downloads/install.sh"] = tpl
        return files

    def render_all(self) -> dict[str, str]:
        files = self.deploy_configs()
        files["inventory.yml"] = self.inventory()
        files[f"group_vars/{self.cfg.env_group}.yml"] = self.group_vars()
        files.update(self.downloads())
        return files

def glue_records(cfg, renderer: Renderer) -> str:
    if cfg.ingress == "private":
        return private_dns_setup(cfg, renderer)
    label, _, parent = cfg.zone.partition(".")
    slots = sorted(renderer._ns_map())
    lines = [f"DNS delegation: add these records in the parent zone {parent}, at whoever hosts it:"]
    for slot, node in sorted(renderer._ns_map().items()):
        lines.append(f"  {slot}.{cfg.zone}  A  {renderer._advertised_ip(node)}"
                     f"    (host \"{slot}.{label}\")")
    lines.append(f"  NS records for {cfg.zone}: " + ", ".join(f"{s}.{cfg.zone}" for s in slots) +
                 f"    (host \"{label}\", one NS record each)")
    lines.append(f"If {cfg.zone} is itself a registered domain, set these at the registrar "
                 "instead: the nameservers above, each with its IP as a glue record.")
    return "\n".join(lines)

def private_dns_setup(cfg, renderer: Renderer) -> str:
    """Private ingress has no registrar glue: the zone is only reachable
    inside the VPC, so resolvers that clients use must forward it to boxd-dns."""
    ns = sorted(renderer._ns_map().items())
    ips = ", ".join(renderer._advertised_ip(node) for _, node in ns)
    lines = [f"DNS setup for private ingress ({cfg.zone} is served only inside the VPC):",
             "  boxd-dns nodes (authoritative for the zone):"]
    lines += [f"    {slot}  {renderer._advertised_ip(node)}" for slot, node in ns]
    lines += [f"  Conditional forwarder: {cfg.zone} -> {ips}",
              "    on your corporate DNS, a Route 53 Resolver outbound rule, or the",
              "    Twingate connector host's resolver.",
              f"  Twingate: resources {cfg.zone} and *.{cfg.zone}; the connector resolves",
              f"    names itself, so it must resolve {cfg.zone} via boxd-dns."]
    return "\n".join(lines)
